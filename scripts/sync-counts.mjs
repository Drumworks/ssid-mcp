#!/usr/bin/env node
// Regenerate the numbers in README.md from https://ssid.ai/compliance/data.json, so the
// README cannot drift from the feed it tells readers to re-query (dropped-recs audit A3,
// 2026-10-31: README said 424 models / 72% while the feed said 550 / 67%).
//
//   node scripts/sync-counts.mjs           rewrite README.md
//   node scripts/sync-counts.mjs --check   exit 1 if README.md differs from the feed
//
// Only two regions are touched: the table between the counts markers, and the single
// `"index": { "total": ... }` line in the check_router_compliance example. Prose is not.
import fs from "node:fs";

const FEED = process.env.SSID_COMPLIANCE_FEED ?? "https://ssid.ai/compliance/data.json";
const README = new URL("../README.md", import.meta.url);
const START = "<!-- counts:start (generated by scripts/sync-counts.mjs) -->";
const END = "<!-- counts:end -->";

export function render(f) {
  const c = f.byCredType;
  const compliant = f.total - c.static;
  const pct = Math.round((compliant / f.total) * 100);
  const table = `${START}
Numbers below were generated from \`${FEED}\` on ${f.generatedAt}. Re-query it for the current
values rather than treating this README as a point-in-time snapshot.

| Metric | Value | Source |
|---|---|---|
| Router / gateway / mesh / AP models tracked | ${f.total} | Manufacturer documentation, per-model cited |
| No longer ship a universal default password | **${pct}%** (${compliant} of ${f.total}) | [Compliance Index](https://ssid.ai/compliance) |
| — set at first setup | ${c["set-on-setup"]} | |
| — unique password on the device label | ${c["label-unique"]} | |
| — app-only admin, no web login | ${c["app-only"]} | |
| — universal default (the risky pattern) | ${c.static} | |
| MAC/OUI vendors indexed | every registered IEEE prefix | IEEE MA-L registry, re-ingested daily at 04:00 |
${END}`;
  return { table, indexLine: `"index": { "total": ${f.total}, "compliantPct": ${f.compliantPct}, "staticCount": ${c.static}, "generatedAt": "${f.generatedAt}",` };
}

export function apply(readme, f) {
  const { table, indexLine } = render(f);
  const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`);
  if (!re.test(readme)) throw new Error("counts markers not found in README.md");
  const lineRe = /"index": \{ "total": \d+, "compliantPct": \d+, "staticCount": \d+, "generatedAt": "[\d-]+",/;
  if (!lineRe.test(readme)) throw new Error("check_router_compliance example index line not found");
  return readme.replace(re, () => table).replace(lineRe, () => indexLine);
}

async function main() {
  const res = await fetch(FEED);
  if (!res.ok) throw new Error(`feed ${res.status}`);
  const f = await res.json();
  if (!f.total || !f.byCredType) throw new Error("feed has no total; refusing");
  const cur = fs.readFileSync(README, "utf8");
  const next = apply(cur, f);
  if (process.argv.includes("--check")) {
    if (cur === next) return console.log(`✓ README matches the feed (${f.total} models, ${f.generatedAt})`);
    console.error(`✗ README is stale against the feed (${f.total} models, ${f.generatedAt}). Run: node scripts/sync-counts.mjs`);
    process.exit(1);
  }
  fs.writeFileSync(README, next);
  console.log(`✓ README updated: ${f.total} models, ${f.generatedAt}`);
}

if (import.meta.url === `file://${process.argv[1]}`) main().catch((e) => { console.error(e.message); process.exit(1); });
